-- Chay script nay tren Supabase SQL Editor (nhom CookBook)
-- Ten cot camelCase giong code mau trananhtin_flutter.app (moTa, hinhAnh, ...)

create table if not exists "Category" (
  id bigint generated by default as identity primary key,
  ten text not null,
  "moTa" text
);

create table if not exists "Recipe" (
  id bigint generated by default as identity primary key,
  ten text not null,
  "moTa" text default '',
  "hinhAnh" text default '',
  "thoiGian" int default 0,
  "danhGia" numeric default 0,
  "idCategory" bigint references "Category"(id),
  "nguyenLieu" text default '',
  "cachLam" text default ''
);

create table if not exists "Favorite" (
  id bigint generated by default as identity primary key,
  "userId" uuid not null references auth.users(id) on delete cascade,
  "recipeId" bigint not null references "Recipe"(id) on delete cascade,
  unique ("userId", "recipeId")
);

-- Bang profile user (hoTen = Display Name tu Supabase Auth)
create table if not exists "User" (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  "hoTen" text
);

alter table "Category" enable row level security;
alter table "Recipe" enable row level security;
alter table "Favorite" enable row level security;
alter table "User" enable row level security;

create policy "Category read all" on "Category" for select using (true);
create policy "Recipe read all" on "Recipe" for select using (true);

create policy "Favorite read own" on "Favorite"
  for select using (auth.uid() = "userId");

create policy "Favorite insert own" on "Favorite"
  for insert with check (auth.uid() = "userId");

create policy "Favorite delete own" on "Favorite"
  for delete using (auth.uid() = "userId");

create policy "User read own" on "User"
  for select using (auth.uid() = id);

create policy "User insert own" on "User"
  for insert with check (auth.uid() = id);

create policy "User update own" on "User"
  for update using (auth.uid() = id);

