-- -----------------------------------------------------------------------------
-- 1. BANG
-- -----------------------------------------------------------------------------

create table if not exists "Category" (
  id bigint generated by default as identity primary key,
  ten text not null,
  "moTa" text
);

create table if not exists "Recipe" (
  id bigint generated by default as identity primary key,
  ten text not null,
  "moTa" text default '',
  "hinhAnh" text default '',
  "thoiGian" int default 0,
  "doKho" int default 2 check ("doKho" >= 1 and "doKho" <= 3),
  "idCategory" bigint references "Category"(id),
  "nguyenLieu" text default '',
  "cachLam" text default ''
);

create table if not exists "Favorite" (
  id bigint generated by default as identity primary key,
  "userId" uuid not null references auth.users(id) on delete cascade,
  "recipeId" bigint not null references "Recipe"(id) on delete cascade,
  unique ("userId", "recipeId")
);

-- Profile: hoTen dong bo tu Auth (metadata hoTen / full_name)
create table if not exists "User" (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  "hoTen" text
);

-- -----------------------------------------------------------------------------
-- 2. INDEX (tuy chon, giup query nhanh hon)
-- -----------------------------------------------------------------------------

create index if not exists "Recipe_idCategory_idx" on "Recipe" ("idCategory");
create index if not exists "Favorite_userId_idx" on "Favorite" ("userId");
create index if not exists "Favorite_recipeId_idx" on "Favorite" ("recipeId");

-- -----------------------------------------------------------------------------
-- 3. RLS
-- -----------------------------------------------------------------------------

alter table "Category" enable row level security;
alter table "Recipe" enable row level security;
alter table "Favorite" enable row level security;
alter table "User" enable row level security;

-- Xoa policy cu neu chay lai script (tranh loi trung ten)
drop policy if exists "Category read all" on "Category";
drop policy if exists "Recipe read all" on "Recipe";
drop policy if exists "Favorite read own" on "Favorite";
drop policy if exists "Favorite insert own" on "Favorite";
drop policy if exists "Favorite delete own" on "Favorite";
drop policy if exists "User read own" on "User";
drop policy if exists "User insert own" on "User";
drop policy if exists "User update own" on "User";

create policy "Category read all" on "Category"
  for select using (true);

create policy "Recipe read all" on "Recipe"
  for select using (true);

create policy "Favorite read own" on "Favorite"
  for select using (auth.uid() = "userId");

create policy "Favorite insert own" on "Favorite"
  for insert with check (auth.uid() = "userId");

create policy "Favorite delete own" on "Favorite"
  for delete using (auth.uid() = "userId");

create policy "User read own" on "User"
  for select using (auth.uid() = id);

create policy "User insert own" on "User"
  for insert with check (auth.uid() = id);

create policy "User update own" on "User"
  for update using (auth.uid() = id);

-- -----------------------------------------------------------------------------
-- 4. QUYEN (grant) — can cho role anon/authenticated doc bang
-- -----------------------------------------------------------------------------

grant usage on schema public to anon, authenticated;

grant select on table "Category" to anon, authenticated;
grant select on table "Recipe" to anon, authenticated;

grant select, insert, update on table "User" to authenticated;
grant select, insert, delete on table "Favorite" to authenticated;

